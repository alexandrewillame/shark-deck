/**
 * Build the Attack Shark keyboard registry from our own extraction of the
 * vendor's Driver v4 (scripts/extract-keyboard-registry.ts).
 *
 *   npm run extract:registry   # read the installed Driver v4 (once per vendor update)
 *   npm run import:kb          # regenerate src/main/devices/catalog/generated/
 *
 * From Driver v4's device table, key grids and factory key matrices:
 *
 *  - every Attack Shark keyboard row -> generated/keyboard-rows.ts
 *  - each board's slot map, every key of its layout's grid matched to the ONE
 *    slot of its factory matrix that types it -> generated/vendor-layouts.ts
 *    (one entry per layout where every board on it has the same map)
 *  - every other layout grid as drawing-only geometry (no slots, so nothing
 *    can address a key through it) -> generated/layout-geometry.ts
 *  - every other brand's model id, for the "Not an Attack Shark device" card
 *    -> generated/foreign-ids.ts
 *  - an append-only id -> slug lock (generated/slugs.lock.json): every
 *    per-model store (profiles, colours, backups) is keyed by slug, so a
 *    renamed slug would orphan a user's data. The script refuses to rename.
 *
 * Boards Driver v4 does not list (newer than the copy read) come from
 * scripts/data/keyboard-rows-outside-v4.json, kept as Shark Deck shipped them
 * until an owner's report or a newer Driver v4 confirms or replaces them.
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import * as prettier from 'prettier';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  convertLayout,
  parseRates,
  parseTravel,
  type VendorLayout,
} from '../src/main/devices/catalog/vendor-layout';
import type { KeyboardFamily, KeyboardRow } from '../src/main/devices/catalog/keyboard-row';
import type { KeyLayoutEntry } from '../src/shared/types/keys';
import { MAGNETIC_SWITCHES } from '../src/shared/keyboard-switches';
import type { DriverV4Registry, DriverV4Row } from './extract-keyboard-registry';

const APP = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const SOURCE = resolve(APP, 'scripts/_raw/driverv4/registry.json');
const OUTSIDE = resolve(APP, 'scripts/data/keyboard-rows-outside-v4.json');
const OUT = resolve(APP, 'src/main/devices/catalog/generated');

/** Ids Driver v4 files under another brand that Attack Shark sells as its own
 *  (3379: the X65 UK board, also sold as WINSTAR RK-X44-68: same internal
 *  name and PCB). */
const ALSO_OURS = new Set([3379]);

/** Ids whose cleaned vendor name is not the retail name. */
const NAME_OVERRIDES: Record<number, string> = {
  2308: 'X65 PRO HE',
  2938: 'X65 PRO HE',
  3379: 'X65 (UK)',
  4244: 'AK029 V2',
};

/** The R85HE predates the lock; its stores are keyed by this slug. */
const LEGACY_SLUGS: Record<number, string> = { 3123: 'attack-shark-r85he' };

export function marketingName(id: number, vendorName: string): string {
  if (NAME_OVERRIDES[id]) return NAME_OVERRIDES[id]!;
  return vendorName
    .replace(/UItra/g, 'Ultra') // vendor typo: capital I for l
    .replace(/ULTRA/g, 'Ultra')
    .replace(/PROHE/g, 'PRO HE')
    .replace(/^([A-Z]+\d+)(?=[A-Za-z])/, '$1 ') // "X68PRO HE" -> "X68 PRO HE"
    .replace(/\bpro\b/g, 'PRO')
    .replace(/(\S)HE\b/g, '$1 HE')
    .replace(/\s+/g, ' ')
    .trim();
}

const kebab = (s: string) =>
  s
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '');

/**
 * The command set, from the chip in the internal name: the YC3121 boards
 * speak the older set (keymap opcode 0x09, drivers/yc500-keyboard.ts), the
 * RY5088, RY6602, RY6609, YC3123 and PAN1086 ones the R85 HE's (0x0A).
 * Anything else is `unknown`, and stays read-only.
 */
export function familyOf(internalName: string): KeyboardFamily {
  if (internalName.startsWith('yc3121_')) return 'yc500';
  if (/^(ry5088|ry6602|ry6609|yc3123|pan1086)_/.test(internalName)) return 'gen2';
  return 'unknown';
}

/** Driver v4 names switches in Chinese; our own table (keyboard-switches.ts) has their ids. */
function switchTypesOf(row: DriverV4Row): { code: number; name: string }[] {
  return row.switchTypes.flatMap((vendorName) => {
    const s = MAGNETIC_SWITCHES.find((m) => m.vendorName === vendorName);
    if (!s)
      console.warn(
        `${row.id} ${row.displayName}: switch "${vendorName}" not in keyboard-switches.ts`,
      );
    return s ? [{ code: s.id, name: s.name }] : [];
  });
}

const banner = (what: string, source: DriverV4Registry['source']) =>
  `// GENERATED by scripts/import-keyboard-registry.ts — do not edit; run \`npm run import:kb\`.\n` +
  `// ${what}\n` +
  `// Source: ${source.app} ${source.version ?? ''} (${source.bundle}), its device table, key\n` +
  `// grids and factory key matrices, read by scripts/extract-keyboard-registry.ts.\n` +
  `// provenance: ported-from-vendor — unverified on hardware except where a\n` +
  `// hand-written descriptor or an owner's recording overlays a row.\n`;

interface Outside {
  rows: KeyboardRow[];
  slotLayouts: Record<string, KeyLayoutEntry[]>;
  geometry: Record<string, KeyLayoutEntry[]>;
  /**
   * Boards Driver v4 does list, on a layout it draws from an SVG picture
   * rather than a key grid (the two K86, X68 MAX, X68 Ultra, X85 Ultra, X65
   * UK): the slot map and drawing Shark Deck shipped for them, by id, until
   * those pictures are read too.
   */
  fallbacks: Record<
    string,
    { slotLayout?: [string, KeyLayoutEntry[]]; geometry?: [string, KeyLayoutEntry[]] }
  >;
}

async function main() {
  if (!existsSync(SOURCE)) {
    throw new Error(`${SOURCE} missing: run \`npm run extract:registry\` against Driver v4 first`);
  }
  const v4 = JSON.parse(readFileSync(SOURCE, 'utf8')) as DriverV4Registry;
  const outside = JSON.parse(readFileSync(OUTSIDE, 'utf8')) as Outside;
  const keyboards = v4.rows.filter((r) => r.type === 'keyboard');
  const isOurs = (r: DriverV4Row) => r.company === 'AttackShark' || ALSO_OURS.has(r.id);
  const ours = keyboards.filter(isOurs).sort((a, b) => a.id - b.id);
  const foreign = v4.rows.filter((r) => !isOurs(r) && r.type === 'keyboard');

  // --- slugs (append-only) -------------------------------------------------
  const lockFile = join(OUT, 'slugs.lock.json');
  const lock: Record<string, string> = existsSync(lockFile)
    ? JSON.parse(readFileSync(lockFile, 'utf8'))
    : {};
  for (const r of ours) {
    const want =
      LEGACY_SLUGS[r.id] ?? `attack-shark-${kebab(marketingName(r.id, r.displayName))}-${r.id}`;
    const have = lock[r.id];
    if (have && have !== want) {
      console.warn(
        `slug for ${r.id} stays "${have}" (would now be "${want}") — slugs never change`,
      );
    } else if (!have) {
      lock[r.id] = want;
    }
  }

  // --- layouts -------------------------------------------------------------
  // Each board's slot map: its grid matched against its own factory matrix.
  // One entry per layout when every board on it maps the same; a board whose
  // map differs, or that cannot be matched, is said so in the report.
  const pictures = v4.layouts as Record<string, VendorLayout>;
  const addressable: Record<string, KeyLayoutEntry[]> = {};
  const geometry: Record<string, KeyLayoutEntry[]> = {};
  const slotLayoutOf = new Map<number, string>();
  const unmatched: string[] = [];
  for (const [stem, picture] of Object.entries(pictures).sort(([a], [b]) => a.localeCompare(b))) {
    geometry[stem] = convertLayout(picture, { geometryOnly: true });
    const maps: [number, KeyLayoutEntry[]][] = [];
    for (const r of ours.filter((x) => x.keyLayout === stem)) {
      const m = v4.matrices[r.id];
      if (!m) {
        unmatched.push(`${r.id} ${r.displayName}: no factory matrix in Driver v4`);
        continue;
      }
      try {
        maps.push([r.id, convertLayout(picture, { defaultMatrix: m })]);
      } catch (e) {
        unmatched.push(`${r.id} ${r.displayName}: ${(e as Error).message}`);
      }
    }
    const same = maps.every(([, l]) => JSON.stringify(l) === JSON.stringify(maps[0]?.[1]));
    for (const [id, l] of maps) {
      const key = same ? stem : `${stem}#${id}`;
      addressable[key] = l;
      slotLayoutOf.set(id, key);
    }
  }

  // Boards on a layout with no grid in Driver v4: what Shark Deck shipped.
  for (const r of ours) {
    const f = outside.fallbacks[r.id];
    if (!f || (r.keyLayout && pictures[r.keyLayout])) continue;
    if (f.slotLayout && !slotLayoutOf.has(r.id)) {
      addressable[f.slotLayout[0]] ??= f.slotLayout[1];
      slotLayoutOf.set(r.id, f.slotLayout[0]);
    }
    if (f.geometry) geometry[f.geometry[0]] ??= f.geometry[1];
  }

  // --- rows ----------------------------------------------------------------
  const rows: KeyboardRow[] = ours.map((r) => ({
    id: r.id,
    slug: lock[r.id]!,
    name: marketingName(r.id, r.displayName),
    vendorName: r.displayName,
    internalName: r.internalName,
    vid: r.vid,
    pid: r.pid,
    family: familyOf(r.internalName),
    layout: r.keyLayout ?? 'Unknown',
    slotLayout: slotLayoutOf.get(r.id) ?? null,
    profiles: r.profiles ?? 1,
    magnetic: r.magnetic,
    travel: parseTravel(r.travel),
    switchReplaceable: r.switchReplaceable,
    switchTypes: switchTypesOf(r),
    screen: r.screen,
    knob: r.knobKeyCodes.length > 0,
    debounce: r.debounce,
    sleep24: r.sleep24,
    sleepBT: r.sleepBT,
    sideLight: r.sideLight,
    rates: parseRates(r.internalName),
    bulkKeymap: false,
  }));

  // Boards newer than the Driver v4 read, as Shark Deck shipped them; their
  // layouts only where the extraction has none of that name.
  const have = new Set(rows.map((r) => r.id));
  for (const r of outside.rows) {
    if (have.has(r.id)) continue;
    if (!lock[r.id]) lock[r.id] = r.slug;
    rows.push({ ...r, slug: lock[r.id]! });
    if (r.slotLayout && !addressable[r.slotLayout] && outside.slotLayouts[r.slotLayout])
      addressable[r.slotLayout] = outside.slotLayouts[r.slotLayout]!;
    if (!geometry[r.layout] && outside.geometry[r.layout])
      geometry[r.layout] = outside.geometry[r.layout]!;
  }
  rows.sort((a, b) => a.id - b.id);

  // --- foreign ids ---------------------------------------------------------
  const ourIds = new Set(rows.map((r) => r.id));
  const others = foreign.filter((r) => !ourIds.has(r.id));
  const brands = [...new Set(others.map((r) => r.company || 'unknown'))].sort();
  const foreignPairs = others
    .map((r) => [r.id, brands.indexOf(r.company || 'unknown')] as const)
    .sort((a, b) => a[0] - b[0]);

  // --- write ---------------------------------------------------------------
  // Through prettier, with the repo's own config: written raw, every re-import
  // would show as a formatting diff after the next `npm run format`.
  const pending = new Map<string, string>();
  const queue = (file: string, text: string) => void pending.set(file, text);
  mkdirSync(OUT, { recursive: true });
  queue(lockFile, JSON.stringify(sortKeys(lock), null, 2) + '\n');
  queue(
    join(OUT, 'keyboard-rows.ts'),
    banner(`${rows.length} Attack Shark keyboard rows.`, v4.source) +
      `import type { KeyboardRow } from '../keyboard-row';\n\n` +
      `export const KEYBOARD_ROWS: KeyboardRow[] = ${JSON.stringify(rows, null, 2)};\n`,
  );
  queue(
    join(OUT, 'vendor-layouts.ts'),
    banner(
      `Addressable layouts: every key carries a firmware slot (col-major, slot = col*6 + row).`,
      v4.source,
    ) +
      `import type { KeyLayoutEntry } from '@shared/types/keys';\n\n` +
      `export const VENDOR_LAYOUTS: Record<string, KeyLayoutEntry[]> = ${JSON.stringify(sortKeys(addressable), null, 2)};\n`,
  );
  queue(
    join(OUT, 'layout-geometry.ts'),
    banner(
      `Drawing-only layouts: NO slots, so nothing can address a key through them.`,
      v4.source,
    ) +
      `import type { KeyLayoutEntry } from '@shared/types/keys';\n\n` +
      `export const LAYOUT_GEOMETRY: Record<string, KeyLayoutEntry[]> = ${JSON.stringify(sortKeys(geometry), null, 2)};\n`,
  );
  queue(
    join(OUT, 'foreign-ids.ts'),
    banner(
      `Model ids the vendor registry gives to OTHER brands, for the read-only card.`,
      v4.source,
    ) +
      `export const FOREIGN_BRANDS: string[] = ${JSON.stringify(brands)};\n\n` +
      `/** [model id, index into FOREIGN_BRANDS], sorted by id. */\n` +
      `export const FOREIGN_IDS: [number, number][] = ${JSON.stringify(foreignPairs)};\n`,
  );
  for (const [file, text] of pending) {
    const options = { ...(await prettier.resolveConfig(file)), filepath: file };
    writeFileSync(file, await prettier.format(text, options));
  }

  // --- report --------------------------------------------------------------
  console.log(
    `${v4.source.app} ${v4.source.version}: ${ours.length} rows read, ${rows.length - ours.length} kept from outside it, ${others.length} foreign ids`,
  );
  console.log(
    `layouts: ${Object.keys(addressable).length} addressable, ${Object.keys(geometry).length} drawings; not in Driver v4's grids: ${v4.missing.layouts.join(', ') || 'none'}`,
  );
  for (const u of unmatched) console.log(`  whole-board only: ${u}`);
  for (const r of rows) {
    console.log(
      `  ${String(r.id).padStart(4)} ${r.family.padEnd(7)} ${r.vid.toString(16)}:${r.pid.toString(16).padStart(4, '0')} ` +
        `${r.magnetic ? 'HE ' : 'mech'} ${r.name.padEnd(14)} ${r.layout.padEnd(28)} ${r.slotLayout ?? (geometry[r.layout] ? 'drawing' : 'none')}`,
    );
  }
}

function sortKeys<T>(o: Record<string, T>): Record<string, T> {
  return Object.fromEntries(
    Object.entries(o).sort((a, b) => {
      const [x, y] = [Number(a[0]), Number(b[0])];
      return Number.isFinite(x) && Number.isFinite(y) ? x - y : a[0].localeCompare(b[0]);
    }),
  );
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
