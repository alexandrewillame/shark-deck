#!/usr/bin/env node
/**
 * Generates docs/MAP.md -- a file index for anyone (or anything) that needs to
 * find where something lives without opening files to see what is in them.
 *
 * Only files at or above THRESHOLD lines are listed: the point is to answer
 * "what is in the big files and roughly where", not to reproduce the tree.
 *
 *   npm run map            regenerate
 *   npm run map -- --check exit 1 if the committed file is stale (used by CI)
 *
 * Export names come from the TypeScript AST rather than a regex, so
 * `export { a, b }`, `export default`, and re-exports are all reported
 * correctly.
 */
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, resolve, sep } from 'node:path';
import ts from 'typescript';

const APP = resolve(import.meta.dirname, '..');
const REPO = resolve(APP, '..');
const OUT = resolve(REPO, 'docs/MAP.md');
const THRESHOLD = 200;

/** Areas in the order they should appear, with a one-line orientation. */
const AREAS = [
  [
    'src/main',
    'Electron main -- the only process that touches HID on the desktop. The device layer here also runs in the browser edition.',
  ],
  ['src/renderer', 'Sandboxed React UI. No Node.'],
  ['src/shared', 'Types, the IPC contract, key layouts, i18n. Imported by all three processes.'],
  ['src/preload', 'contextBridge surfaces.'],
  [
    'src/web',
    'The browser edition (GitHub Pages, WebHID): the in-page host that replaces main + preload.',
  ],
  ['scripts', 'Build helpers, protocol extraction, hardware probes.'],
];

function walk(dir) {
  const out = [];
  let entries;
  try {
    entries = readdirSync(dir, { withFileTypes: true });
  } catch {
    return out;
  }
  for (const e of entries) {
    const p = join(dir, e.name);
    if (e.isDirectory()) {
      if (e.name === '_raw' || e.name === 'node_modules') continue;
      out.push(...walk(p));
    } else if (/\.(ts|tsx|mjs)$/.test(e.name)) {
      out.push(p);
    }
  }
  return out;
}

/** Exported symbol names, via the AST. */
function exportsOf(absPath, text) {
  if (absPath.endsWith('.mjs')) return [];
  const sf = ts.createSourceFile(absPath, text, ts.ScriptTarget.ES2022, true);
  const names = new Set();

  const nameOf = (n) => (n && ts.isIdentifier(n) ? n.text : null);

  sf.forEachChild((node) => {
    const exported = node.modifiers?.some((m) => m.kind === ts.SyntaxKind.ExportKeyword);

    if (exported) {
      if (
        ts.isFunctionDeclaration(node) ||
        ts.isClassDeclaration(node) ||
        ts.isInterfaceDeclaration(node) ||
        ts.isTypeAliasDeclaration(node) ||
        ts.isEnumDeclaration(node)
      ) {
        const n = nameOf(node.name);
        if (n) names.add(n);
      } else if (ts.isVariableStatement(node)) {
        for (const d of node.declarationList.declarations) {
          const n = nameOf(d.name);
          if (n) names.add(n);
        }
      }
    }

    // `export { a, b }` and `export { x } from './y'`
    if (ts.isExportDeclaration(node) && node.exportClause && ts.isNamedExports(node.exportClause)) {
      for (const el of node.exportClause.elements) names.add(el.name.text);
    }
  });

  return [...names];
}

const rows = [];
for (const [area] of AREAS) {
  for (const abs of walk(resolve(APP, area))) {
    const rel = relative(APP, abs).split(sep).join('/');
    if (/\.test\.(ts|tsx)$/.test(rel)) continue;
    const text = readFileSync(abs, 'utf8');
    const lines = text.split('\n').length;
    if (lines < THRESHOLD) continue;
    rows.push({ area, rel, lines, exports: exportsOf(abs, text) });
  }
}
rows.sort((a, b) => b.lines - a.lines);

const totalFiles = AREAS.flatMap(([a]) => walk(resolve(APP, a))).filter(
  (p) => !/\.test\.(ts|tsx)$/.test(p),
).length;

const out = [];
out.push('# File map');
out.push('');
out.push('<!-- GENERATED by app/scripts/gen-map.mjs. Do not hand-edit: run `npm run map`. -->');
out.push('');
out.push(
  `Every non-test source file of ${THRESHOLD} lines or more, largest first, with what it ` +
    'exports. Read this instead of opening files to find out what is in them.',
);
out.push('');
out.push(
  `${rows.length} of ${totalFiles} source files are at or above ${THRESHOLD} lines. ` +
    'Anything not listed here is small enough to read whole.',
);
out.push('');

out.push('## Largest first');
out.push('');
out.push('| Lines | File | Exports |');
out.push('|---:|---|---|');
for (const r of rows.slice(0, 25)) {
  const ex = r.exports.length
    ? r.exports.slice(0, 12).join(', ') +
      (r.exports.length > 12 ? `, +${r.exports.length - 12}` : '')
    : '_(none)_';
  out.push(`| ${r.lines} | \`${r.rel}\` | ${ex} |`);
}
out.push('');

for (const [area, blurb] of AREAS) {
  const mine = rows.filter((r) => r.area === area);
  if (!mine.length) continue;
  out.push(`## ${area}`);
  out.push('');
  out.push(`${blurb}`);
  out.push('');
  out.push('| Lines | File | Exports |');
  out.push('|---:|---|---|');
  for (const r of mine) {
    const ex = r.exports.length
      ? r.exports.slice(0, 12).join(', ') +
        (r.exports.length > 12 ? `, +${r.exports.length - 12}` : '')
      : '_(none)_';
    out.push(`| ${r.lines} | \`${r.rel}\` | ${ex} |`);
  }
  out.push('');
}

const body = out.join('\n');

if (process.argv.includes('--check')) {
  let existing = '';
  try {
    existing = readFileSync(OUT, 'utf8');
  } catch {
    /* missing counts as stale */
  }
  if (existing.trimEnd() !== body.trimEnd()) {
    console.error('docs/MAP.md is out of date. Run: npm run map');
    process.exit(1);
  }
  console.log('docs/MAP.md is up to date.');
  process.exit(0);
}

writeFileSync(OUT, `${body}\n`);
const bytes = statSync(OUT).size;
console.log(`docs/MAP.md: ${rows.length} files listed, ${(bytes / 1024).toFixed(1)} kB`);
