import { RECORDED_KEYMAPS } from './catalog/recorded-keymaps';

/**
 * The R98 HE's key map (model id 3743, firmware 5.06) as its owner's recording
 * shows the vendor software reading it when it opened, before any key was
 * remapped: the factory map. The base layer is GET_KEYMATRIX (0x8A) pages 0–7,
 * the Fn layer GET_FN (0x90) pages 0–7 for Windows: 64 data bytes a page, a
 * four-byte binding a slot.
 */
