export interface KeyRef {
  row: number;
  col: number;
}

const KEY_U_DEFAULT = 34; // px per 1u, used until a `fit` measurement lands
/** Board gutter as a fraction of the unit — 12px at the 34px default. */
const PAD_RATIO = 12 / 34;
const KEY_U_MIN = 22;
const KEY_U_MAX = 46;

/**
 * The visual gap between adjacent keycaps, in key-units.
 *
 * A real board's pitch is 19.05 mm and a cap is ~18 mm, so the gutter is
 * ~0.07u per side — 0.13u between two caps. Everything else (key height, the
 * board's own height) is derived from this one number, which is what makes a
 * 1u key SQUARE: `1u - GAP_U` wide by `1u - GAP_U` tall.
 *
 * It used to be a hardcoded 40px tall key on a 34px unit with a 4px gutter,
 * and the gutter was subtracted from a width that one of the two layouts had
 * already subtracted it from (see `bakedGapOf`). A 1u key therefore came out
 * 0.75u wide by 1.18u tall — half again taller than wide, which is why the
 * board never read as a keyboard.
 */
export const GAP_U = 0.13;
const RADIUS_RATIO = 6 / KEY_U_DEFAULT;
const FONT_RATIO = 10 / KEY_U_DEFAULT;

/**
 * How much inter-key gutter a layout has already baked into its own `w`.
 *
 * The two layouts disagree. `ANSI_75` is generated by a `row()` helper with
 * contiguous `x` and `w: 1`, so a 1u key is a full unit wide and the gutter
 * has to be drawn. `ANSI_79_SG9047` is vendor-extracted and spells the same
 * key as `w: 0.87` at a 1.0 pitch — the gutter is already in the numbers.
 *
 * Measured, not configured: the smallest non-negative slack between two
 * horizontally adjacent keys is the inter-key gutter. The deliberate cluster
 * gaps a vendor layout also encodes (before the arrow block, between F4 and
 * F5) are strictly larger, so the minimum picks out the right one.
 */
export function bakedGapOf(keys: KeyLayoutEntry[]): number {
  const byRow = new Map<number, KeyLayoutEntry[]>();
  for (const k of keys) {
    if (!byRow.has(k.y)) byRow.set(k.y, []);
    byRow.get(k.y)!.push(k);
  }
  let min = Infinity;
  for (const ks of byRow.values()) {
    const sorted = [...ks].sort((a, b) => a.x - b.x);
    for (let i = 1; i < sorted.length; i++) {
      const prev = sorted[i - 1]!;
      const slack = sorted[i]!.x - (prev.x + (prev.w ?? 1));
      if (slack >= 0 && slack < min) min = slack;
    }
  }
  return min === Infinity ? 0 : Math.min(min, GAP_U);
}

/** Keys that read better as their real keycap glyph than a spelled-out
 *  label — the rest (letters, digits, symbols, ESC/CAPS/etc.) stay text.
 *  Keyed by the layout's legend, so it covers every board in the app. */
const KEY_ICON: Partial<Record<string, IconName>> = {
  Up: 'arrowUp',
  Down: 'arrowDown',
  Left: 'arrowLeft',
  Right: 'arrowRight',
  Bksp: 'backspace',
  // The ↵ printed on the key — not `arrowReturn`, the curl the topbar uses
  // for "home", which read as that here.
  Enter: 'enterKey',
  TAB: 'tabKey',
  SHIFT: 'shiftKey',
};

/** A stable 0..1 per key: the same key gets the same value every render. */
const keyNoise = (a: number, b: number) => {
  const n = Math.sin(a * 127.1 + b * 311.7) * 43758.5453;
  return n - Math.floor(n);
};

/**
 * One key's flicker beat: its own period (3.5-8s) and a negative delay, so
 * every key starts part-way through its cycle and no two keys pulse together.
 * Deterministic per key, so a re-render never restarts the animation.
 */
export function flickerTiming(row: number, col: number): { dur: number; delay: number } {
  const dur = 3.5 + 4.5 * keyNoise(row, col);
  return { dur, delay: -dur * keyNoise(col + 17, row + 31) };
}

const flickerVars = (row: number, col: number) => {
  const { dur, delay } = flickerTiming(row, col);
  return {
    ['--kf-dur' as string]: `${dur.toFixed(2)}s`,
    ['--kf-delay' as string]: `${delay.toFixed(2)}s`,
  };
};

/** The glyph a board draws for this legend, if it draws one — so a keycap
 *  drawn elsewhere (a panel heading naming the selected key) matches it. */
export function legendIcon(label: string): IconName | undefined {
  return KEY_ICON[label];
}

/** A vertical per-key gauge (actuation depth, release point, dead zones) —
 *  see MagneticSection.tsx's whole-board overlay. `fillPct`/ticks/bands are
 *  0..100 positions from the TOP of the gauge track. */
export interface KeyGauge {
  fillPct: number;
  ticks?: { pct: number; color: string }[];
  bands?: { fromPct: number; toPct: number; color: string }[];
}

/**
 * Shared interactive keyboard map. `layout` defaults to the pragmatic ANSI-75
 * used when a device carries no matrix of its own. `cap` paints an overlay on
 * each key (a colour swatch, a bound-key label, a mode dot…); `accent` returns a
 * CSS colour to tint the key body (per-key lighting, live travel heat);
 * `gauge` draws a small vertical actuation/release/dead-zone readout on the
 * key (Actuation tab's whole-board overlay).
 *
 * `fit`: when true (the default for a full-board view — Lighting's global
 * pane, the Actuation tab), a `ResizeObserver` scales the per-unit key size
 * to fill the container's width instead of a fixed 34px/unit, so the board
 * is centred and uses the whole available width rather than a fixed-size
 * island floating in a wide pane.
 *
 * The forwarded ref points at `.kbmap` — the actual bordered board box, sized
 * in key-units and centred — not the full-width `.kbmap-wrap` around it. A caller wrapping this in `<ArtAnchor mode="keyboard" measureRef={...}>`
 * needs that inner box specifically: the travelling photo has to land on
 * where the board visually is, not on the wider strip reserved so `fit`
 * above has room to compute against.
 */
/**
 * How far the pointer must travel before a press counts as a drag.
 *
 * Eight pixels, not four: below that a click on a trackpad routinely moves far
 * enough to arm a drag, and while a drag could rewrite a key that made an
 * ordinary click a coin toss. It cannot any more (see `onKeyToGroup`), but the
 * threshold has no reason to sit at the edge of a hand tremor either.
 */
const DRAG_MIN_PX = 8;

export const KeyboardMap = forwardRef<
  HTMLDivElement,
  {
    layout?: KeyLayoutEntry[];
    selected?: KeyRef | null;
    /** Takes precedence over `selected` when given — lets a caller highlight
     *  more than one key at once (the Actuation tab's multi-select). */
    isSelected?: (k: KeyLayoutEntry) => boolean;
    onSelect?: (k: KeyRef, mods: { shift: boolean; ctrl: boolean }) => void;
    /** called on click and on drag-enter while the mouse button is held */
    onPaint?: (k: KeyRef) => void;
    /**
     * Rubber-band selection: drag from the board's background and every key the
     * box touches is reported on release. Lives here rather than in each
     * consumer because this component owns the geometry — keys are positioned
     * from their own `x`/`w` in key-units against `--kb-u`, so nothing outside
     * can hit-test them without duplicating that.
     *
     * Starts only on the BACKGROUND, never on a key, so it cannot swallow a
     * plain click or a paint drag.
     */
    onMarquee?: (keys: KeyRef[], mods: { shift: boolean; ctrl: boolean }) => void;
    /**
     * Let a marquee begin ON a key, not only on the board's background.
     *
     * This is what people actually do — you drag across the keys you want,
     * you do not hunt for a gap first — but it cannot be the default, because
     * a pane that paints (per-key lighting) needs a drag from a key to mean
     * "paint along this path". So: the Actuation tab sets it, and per-key
     * lighting sets it only while its rectangle tool is armed.
     *
     * With this on, a press on a key defers its selection to pointerup: move
     * past the drag threshold and the gesture is a marquee instead, so a
     * drag never leaves a stray single-key selection behind it.
     */
    marqueeFromKeys?: boolean;
    /**
     * On a painting board, the box takes Shift or Ctrl.
     *
     * Per-key lighting's plain press paints, so its box is a modifier gesture
     * there — the same Shift/Ctrl the Actuation board's marquee takes. Read
     * off the press itself, not off a "held" flag kept elsewhere, so a keyup
     * lost to Alt-Tab can never leave the board stuck in box mode. A plain
     * press on the board's background starts nothing.
     */
    marqueeOnModifier?: boolean;
    /**
     * Drop a key on something: another key, or a group row.
     *
     * Both mean "this key's settings belong over there". Dropping on a key is
     * a device write with no confirmation, so it has to be a gesture nobody
     * performs by accident — and for a while it was not: while an unmodified
     * drag ALSO had to serve as the marquee, dragging across the keys you
     * wanted to select instead copied the first one over all of them, and a
     * board of individually tuned keys came back holding one setting. What
     * makes it safe now is that the two gestures are separate — the marquee
     * takes shift or ctrl, so a plain drag can only ever mean "I have hold of
     * this key" — and that the drag has a threshold and a keycap following the
     * cursor saying what is in flight.
     *
     * Pointer events throughout rather than HTML5 drag-and-drop: the two
     * cannot share a board. `draggable` hands the gesture to the browser on
     * the first pointermove, which stops pointermove being delivered at all —
     * that is what previously broke the marquee on this very board.
     */
    onKeyDrop?: (from: KeyLayoutEntry, to: { key?: KeyRef; groupId?: string }) => void;
    /** Double-click on a key. The Actuation tab selects that key's whole group
     *  — "the others that are set up like this one", which is a question the
     *  board can answer directly instead of sending you to the rail. */
    onKeyDoubleClick?: (k: KeyLayoutEntry) => void;
    /** How many keys a drag carries, for the ghost's "+N". */
    selectedCount?: number;
    cap?: (k: KeyLayoutEntry) => ReactNode;
    /**
     * Make keys draggable, for dropping one onto something else (a key group).
     *
     * Opt-in because HTML5 drag and the marquee both start from a press on a
     * key: with this on, a `dragstart` cancels any marquee the same gesture had
     * begun, since the browser stops sending pointermove once a drag takes
     * over and the rubber band would otherwise be left on screen.
     */
    onKeyDragStart?: (k: KeyLayoutEntry, e: ReactDragEvent<HTMLDivElement>) => void;
    /**
     * Hover text for one key.
     *
     * Lives here rather than in `cap` because `.kbkey-cap` is a small
     * `pointer-events: none` box in the key's top-right corner — anything
     * rendered through `cap` cannot receive a hover at all, which is why the
     * remap pane's "reserved key" tooltip never opened. This renders a hit
     * layer over the whole key instead.
     */
    tip?: (k: KeyLayoutEntry) => string | undefined;
    accent?: (k: KeyLayoutEntry) => string | undefined;
    gauge?: (k: KeyLayoutEntry) => KeyGauge | undefined;
    /** false renders a look-only board — no pointer cursor, no hover border,
     *  no click/paint handlers (the global keyboard-lighting preview). */
    interactive?: boolean;
    fit?: boolean;
    /**
     * Drop the board's gutter, border and background — the board becomes just
     * its keys.
     *
     * A prop rather than a stylesheet override because the box's width and
     * height are inline, computed FROM the gutter: a caller that hid the
     * gutter in CSS still got a box sized as though it were there.
     */
    bare?: boolean;
    /**
     * A lighting effect is painting these keys, so their labels need to stay
     * readable over any colour it chooses.
     *
     * Split out of `interactive={false}`, which was doing both jobs: the
     * Actuation Test board is non-interactive and NOT painted by an effect, so
     * it inherited white, shadowed labels while every other board in the tab
     * had dark ones on a light keycap. Same board, same tab, two different
     * keycaps — which is what made the Test view look like a different app.
     */
    lit?: boolean;
    /**
     * Draw lit keys as real LEDs do: each one dimming up and down a little, on
     * its own slow, irregular beat. Only meaningful with `lit`. Pure CSS (see
     * keyboard-map.css), so it costs no renders, and off under reduced motion.
     */
    flicker?: boolean;
    /**
     * Render at an exact px-per-unit instead of the 34px default or a `fit`
     * measurement. Everything else scales with it, so the result is the same
     * board at another size — which is what the lighting library's row
     * thumbnails and hover previews want.
     */
    keyU?: number;
    /** Hide the printed legend on every cap (the thumbnails, where a label
     *  would be illegible and is noise in a colour preview anyway). */
    showLabels?: boolean;
  }
>(function KeyboardMap(
  {
    layout,
    selected,
    isSelected,
    onSelect,
    onPaint,
    onMarquee,
    marqueeFromKeys,
    marqueeOnModifier,
    onKeyDrop,
    onKeyDoubleClick,
    selectedCount,
    cap,
    tip,
    accent,
    gauge,
    onKeyDragStart,
    interactive = true,
    fit = true,
    bare = false,
    lit = false,
    flicker = false,
    keyU: keyUProp,
    showLabels = true,
  },
  forwardedRef,
) {
  const keys = useMemo(() => (layout && layout.length ? layout : ANSI_75), [layout]);

  // Rows keep their own `y`: they are positioned by it, exactly as keys are
  // positioned by their `x`. A vendor layout spaces the F-row 1.2u from the
  // number row rather than 1.0u, and stacking rows in document order threw
  // that away — the board lost the one vertical gap a real 75% has.
  const rows = useMemo(() => {
    const byRow = new Map<number, KeyLayoutEntry[]>();
    for (const k of keys) {
      if (!byRow.has(k.y)) byRow.set(k.y, []);
      byRow.get(k.y)!.push(k);
    }
    return [...byRow.entries()].sort((a, b) => a[0] - b[0]).map(([y, ks]) => ({ y, ks }));
  }, [keys]);

  const bakedGap = useMemo(() => bakedGapOf(keys), [keys]);

  // Horizontal span of the WHOLE board, in key-units, from every key's real
  // `x`/`w` — not just the widest row's own w-sum (the previous formula).
  // A vendor-captured layout (ANSI_79_SG9047) bakes deliberate gaps *into*
  // `x` itself — the F1-4/F5-8/F9-12 clusters, the gap before the arrow
  // cluster — to keep columns aligned down the board; positioning key-by-key
  // from that same `x` (below) is what actually reproduces those gaps and
  // that alignment, and this is the matching span for the fit-to-width
  // calculation and every row's own box. The little inter-key gap itself is
  // still handled separately (in px) by `compute` below and each key's own
  // inline style, so this is purely the geometry `x`/`w` already encode.
  const xBounds = useMemo(() => {
    let min = Infinity;
    let max = -Infinity;
    for (const k of keys) {
      if (k.x < min) min = k.x;
      const end = k.x + (k.w ?? 1);
      if (end > max) max = end;
    }
    return { min, span: max - min };
  }, [keys]);

  // The same thing vertically. Every key is 1u tall (KeyLayoutEntry has no
  // height), so a row owns the cell [y, y + 1) and the board spans the last
  // row's bottom — including the extra 0.2u a layout may put above the number
  // row. No `bakedGap` here: a vendor layout bakes the gutter into `w` only,
  // never into `y`, so the vertical gutter is always the full GAP_U.
  const yBounds = useMemo(() => {
    let min = Infinity;
    let max = -Infinity;
    for (const k of keys) {
      if (k.y < min) min = k.y;
      if (k.y + 1 > max) max = k.y + 1;
    }
    return { min, span: max - min };
  }, [keys]);

  const wrapRef = useRef<HTMLDivElement>(null);
  const [keyU, setKeyU] = useState(KEY_U_DEFAULT);
  // Layout effect, not a plain effect: a plain effect runs after the browser
  // already painted this board once at the KEY_U_DEFAULT fallback size, so a
  // caller measuring the board for something else (ArtAnchor's
  // `measureRef`, chasing the travelling photo onto this board's rect) would
  // capture that wrong, pre-fit size on the very first frame and only get
  // the real one a frame later — reads as a jump/snap right as the photo
  // starts moving here. A layout effect computes and applies the real size
  // before that first paint instead, so there's nothing to correct.
  useLayoutEffect(() => {
    // An explicit size wins over both the default and the fit measurement.
    if (keyUProp !== undefined) {
      setKeyU(keyUProp);
      return;
    }
    if (!fit) {
      setKeyU(KEY_U_DEFAULT);
      return;
    }
    const el = wrapRef.current;
    if (!el || typeof ResizeObserver === 'undefined') return;
    const compute = (width: number) => {
      // The board's inline width is `u * span + 2 * pad + 2 * border`, and the
      // gutter is itself `u * PAD_RATIO` — so solving for u divides by the
      // span PLUS the gutter's share of it, and only the 1px border either
      // side is a constant. (It was a flat `width - 26`, from when the gutter
      // was a fixed 12px; that is still the answer it gives at u = 34.)
      const u = (width - 2) / Math.max(1, xBounds.span + 2 * PAD_RATIO);
      setKeyU(Math.max(KEY_U_MIN, Math.min(KEY_U_MAX, u)));
    };
    compute(el.clientWidth);
    const ro = new ResizeObserver((entries) => {
      const w = entries[0]?.contentRect.width;
      if (w) compute(w);
    });
    ro.observe(el);
    return () => ro.disconnect();
  }, [fit, keyUProp, xBounds.span]);

  // Marquee state. The rect is kept in the board's own client coordinates so
  // it can be drawn as a plain absolutely-positioned overlay, and hit-testing
  // uses each key's live `getBoundingClientRect` rather than recomputing the
  // key-unit maths — the DOM already did that.
  const boardRef = useRef<HTMLDivElement | null>(null);
  const dragFrom = useRef<{ x: number; y: number } | null>(null);
  const [box, setBox] = useState<{ x: number; y: number; w: number; h: number } | null>(null);

  /**
   * The drag ghost — a keycap following the cursor while one is in flight.
   *
   * Without it the gesture was a cursor change and nothing else: no indication
   * of WHAT was picked up, which on a 79-key board is the only question that
   * matters. Lives outside React because it tracks the pointer at pointer-move
   * rate; re-rendering the board for that would be absurd.
   */
  const ghostRef = useRef<HTMLElement | null>(null);
  const showGhost = useCallback(
    (label: string, color: string | undefined, dragCount: number, x: number, y: number) => {
      if (!ghostRef.current) {
        const el = document.createElement('div');
        el.className = 'kdrag-ghost';
        // The key's own colour comes with it, because the colour IS what is
        // being dropped: the group, and so the settings, the key belongs to. A
        // ghost reading "S" in the default keycap grey says which key you have
        // hold of and nothing about what letting go will do to the one under
        // the cursor.
        if (color) {
          el.style.background = color;
          el.style.borderColor = color;
          const text = readableTextOn(color);
          if (text) el.style.color = text;
        }
        const cap = document.createElement('span');
        cap.className = 'kdrag-ghost-label';
        cap.textContent = label;
        el.appendChild(cap);
        // Every key coming along, not just the one grabbed: dragging one of a
        // selection carries the whole selection, and the count is the only way
        // to see that before letting go.
        if (dragCount > 1) {
          const more = document.createElement('span');
          more.className = 'kdrag-ghost-more';
          more.textContent = `+${dragCount - 1}`;
          el.appendChild(more);
        }
        document.body.appendChild(el);
        document.documentElement.setAttribute('data-kdrag', '');
        ghostRef.current = el;
      }
      ghostRef.current.style.left = `${x + 12}px`;
      ghostRef.current.style.top = `${y + 12}px`;
    },
    [],
  );
  const hideGhost = useCallback(() => {
    ghostRef.current?.remove();
    ghostRef.current = null;
    document.documentElement.removeAttribute('data-kdrag');
    for (const p of Array.from(document.querySelectorAll('.kdrag-over')))
      p.classList.remove('kdrag-over');
  }, []);
  useEffect(() => hideGhost, [hideGhost]);

  /** What is under the pointer that a key could be dropped on. A group row
   *  wins over a key, since a rail laid over the board would otherwise be
   *  unreachable. */
  const dropTargetAt = (x: number, y: number): { key?: KeyRef; groupId?: string } => {
    const el = document.elementFromPoint(x, y) as HTMLElement | null;
    const groupRow = el?.closest('[data-group-id]') as HTMLElement | null;
    if (groupRow?.dataset.groupId) return { groupId: groupRow.dataset.groupId };
    const keyEl = el?.closest('.kbkey') as HTMLElement | null;
    if (!keyEl) return {};
    const row = Number(keyEl.dataset.row);
    const col = Number(keyEl.dataset.col);
    return Number.isFinite(row) && Number.isFinite(col) ? { key: { row, col } } : {};
  };
  /** Light up whatever the key would land on. */
  const markDropTarget = (x: number, y: number) => {
    const el = document.elementFromPoint(x, y) as HTMLElement | null;
    const target = el?.closest('[data-group-id], .kbkey');
    for (const p of Array.from(document.querySelectorAll('.kdrag-over')))
      if (p !== target) p.classList.remove('kdrag-over');
    target?.classList.add('kdrag-over');
  };

  /**
   * One press, two possible gestures — and neither of them writes to a key.
   *
   * Dragging across the board rubber-bands a selection, which is what dragging
   * across things means everywhere else. Dragging OFF the board onto a group
   * row moves the key there. The two are told apart by where the pointer is,
   * not by a modifier, so nothing has to be learned and nothing is a slip
   * away from the other.
   *
   * What is deliberately gone: a plain drag from key A to key B used to copy
   * A's settings onto B. It shared the marquee's four-pixel threshold and had
   * no confirmation, so the ordinary gesture for "select these keys" silently
   * flattened them onto one setting.
   */
  const onBoardPointerDown = useCallback(
    (e: React.PointerEvent<HTMLDivElement>) => {
      if (!interactive || e.button !== 0) return;
      const onKey = (e.target as HTMLElement).closest('.kbkey') as HTMLElement | null;
      const withMod = e.shiftKey || e.ctrlKey || e.metaKey;
      const entry = onKey
        ? keys.find(
            (k) => k.row === Number(onKey.dataset.row) && k.col === Number(onKey.dataset.col),
          )
        : undefined;
      /**
       * A plain press on a key drags it; the marquee takes shift or ctrl.
       *
       * Dragging is the direct manipulation — you have hold of that key — so it
       * is what an unmodified drag does, and the modifier goes on the bulk
       * gesture, where it already meant "add to the selection". This is only
       * safe now that a drag can land on nothing but a group row: while it
       * could also drop onto another KEY and copy settings there, an
       * unmodified drag was one slip away from rewriting the board, so the
       * two were the other way round.
       */
      const canDrag = !!(onKeyDrop && entry && !withMod);

      if (canDrag || !onMarquee) {
        // Either this press is a key drag, or this board has no marquee at all
        // (per-key lighting paints instead) and a key drag is its only gesture.
        if (!canDrag) return;
        const color = accent?.(entry!);
        const move = (ev: PointerEvent) => {
          if (Math.hypot(ev.clientX - e.clientX, ev.clientY - e.clientY) < DRAG_MIN_PX) return;
          showGhost(entry!.label, color, selectedCount ?? 1, ev.clientX, ev.clientY);
          markDropTarget(ev.clientX, ev.clientY);
        };
        const up = (ev: PointerEvent) => {
          window.removeEventListener('pointermove', move);
          window.removeEventListener('pointerup', up);
          window.removeEventListener('pointercancel', up);
          const dragged = !!ghostRef.current;
          hideGhost();
          if (!dragged) {
            // Never travelled far enough to be a drag, so it was a click on
            // that key. Selection is deferred to here rather than done on
            // pointerdown precisely because the same press might have become a
            // drag — selecting first and dragging after left the key you
            // grabbed selected on top of whatever you actually wanted.
            onSelect?.(
              { row: entry!.row, col: entry!.col },
              { shift: ev.shiftKey, ctrl: ev.ctrlKey || ev.metaKey },
            );
            return;
          }
          const to = dropTargetAt(ev.clientX, ev.clientY);
          // Onto itself is a drag that changed its mind, not an instruction to
          // copy a key over itself.
          if (to.groupId || (to.key && (to.key.row !== entry!.row || to.key.col !== entry!.col)))
            onKeyDrop!(entry!, to);
        };
        window.addEventListener('pointermove', move);
        window.addEventListener('pointerup', up);
        window.addEventListener('pointercancel', up);
        return;
      }

      // A painting board's box is Shift/Ctrl + drag; a plain press there is a
      // paint stroke on a key and nothing at all on the background.
      const modBox = !!marqueeOnModifier && withMod;
      if (marqueeOnModifier && !marqueeFromKeys && !modBox) return;
      // A press on a key is that key's own business (click, or a paint stroke)
      // unless this board lets a marquee start from one.
      if (onKey && !marqueeFromKeys && !modBox) return;
      const host = boardRef.current;
      if (!host) return;
      const r = host.getBoundingClientRect();
      // Remembered so a press that never becomes a drag can still select the
      // key it started on, on release.
      const startedOn: KeyRef | null =
        onKey && Number.isFinite(Number(onKey.dataset.row))
          ? { row: Number(onKey.dataset.row), col: Number(onKey.dataset.col) }
          : null;
      dragFrom.current = { x: e.clientX - r.left, y: e.clientY - r.top };
      setBox({ x: dragFrom.current.x, y: dragFrom.current.y, w: 0, h: 0 });

      const move = (ev: PointerEvent) => {
        const from = dragFrom.current;
        if (!from) return;
        const cx = ev.clientX - r.left;
        const cy = ev.clientY - r.top;
        setBox({
          x: Math.min(from.x, cx),
          y: Math.min(from.y, cy),
          w: Math.abs(cx - from.x),
          h: Math.abs(cy - from.y),
        });
      };
      const up = (ev: PointerEvent) => {
        window.removeEventListener('pointermove', move);
        window.removeEventListener('pointerup', up);
        window.removeEventListener('pointercancel', up);
        const from = dragFrom.current;
        dragFrom.current = null;
        setBox(null);
        if (!from) return;
        const x1 = Math.min(from.x, ev.clientX - r.left);
        const y1 = Math.min(from.y, ev.clientY - r.top);
        const x2 = Math.max(from.x, ev.clientX - r.left);
        const y2 = Math.max(from.y, ev.clientY - r.top);
        // Below the threshold the gesture was a click, not a drag: on a key
        // that means "select this one", on the background it means nothing.
        if (Math.hypot(x2 - x1, y2 - y1) < DRAG_MIN_PX) {
          if (startedOn)
            onSelect?.(startedOn, { shift: ev.shiftKey, ctrl: ev.ctrlKey || ev.metaKey });
          return;
        }
        const hit: KeyRef[] = [];
        for (const el of Array.from(host.querySelectorAll<HTMLElement>('.kbkey'))) {
          const kr = el.getBoundingClientRect();
          const kx1 = kr.left - r.left;
          const ky1 = kr.top - r.top;
          if (kx1 < x2 && kx1 + kr.width > x1 && ky1 < y2 && ky1 + kr.height > y1) {
            const row = Number(el.dataset.row);
            const col = Number(el.dataset.col);
            if (Number.isFinite(row) && Number.isFinite(col)) hit.push({ row, col });
          }
        }
        if (hit.length) onMarquee(hit, { shift: ev.shiftKey, ctrl: ev.ctrlKey || ev.metaKey });
      };
      window.addEventListener('pointermove', move);
      window.addEventListener('pointerup', up);
      window.addEventListener('pointercancel', up);
    },
    [
      interactive,
      onMarquee,
      marqueeFromKeys,
      marqueeOnModifier,
      onSelect,
      onKeyDrop,
      accent,
      keys,
      selectedCount,
      showGhost,
      hideGhost,
    ],
  );

  return (
    <div ref={wrapRef} className={`kbmap-wrap ${fit ? 'kbmap-fit' : ''}`}>
      <div
        ref={(el) => {
          boardRef.current = el;
          if (typeof forwardedRef === 'function') forwardedRef(el);
          else if (forwardedRef) forwardedRef.current = el;
        }}
        className={`kbmap ${interactive ? '' : 'kbmap-static'} ${lit ? 'kbmap-lit' : ''} ${lit && flicker ? 'kbmap-flicker' : ''} ${bare ? 'kbmap-bare' : ''} ${onMarquee ? 'kbmap-marquee-host' : ''}`}
        style={{
          ['--kb-u' as string]: `${keyU}px`,
          // Horizontal gutter: only what the layout has not already taken out
          // of its own `w`. Vertical gutter: always the full GAP_U, since no
          // layout bakes one into `y`.
          ['--kb-gap' as string]: `${Math.max(0, keyU * (GAP_U - bakedGap))}px`,
          ['--kb-vgap' as string]: `${keyU * GAP_U}px`,
          ['--kb-h' as string]: `${keyU * (1 - GAP_U)}px`,
          ['--kb-radius' as string]: `${keyU * RADIUS_RATIO}px`,
          ['--kb-font' as string]: `${keyU * FONT_RATIO}px`,
          // The board's gutter is part of the board, so it scales with it. Fixed
          // at 12px it swallowed a thumbnail whole.
          ['--kb-pad' as string]: bare ? '0px' : `${Math.max(2, Math.round(keyU * PAD_RATIO))}px`,
          ['--kb-bd' as string]: bare ? '0px' : '1px',
          // Rows are absolutely positioned, so the board has no auto size of
          // its own: both axes are the key-unit span plus the board's own
          // padding and 1px border (everything here is border-box).
          // `--kb-pad` / `--kb-bd` rather than the literals they default to:
          // a caller that strips the board's gutter and border (the saved-layout
          // thumbnails do) has to strip them from the SIZE too, or the box stays
          // 26px bigger than the keys in it and the preview floats in a margin.
          width: `calc(var(--kb-u) * ${xBounds.span} + var(--kb-pad) * 2 + var(--kb-bd) * 2)`,
          height: `calc(var(--kb-u) * ${yBounds.span} + var(--kb-pad) * 2 + var(--kb-bd) * 2)`,
        }}
        onPointerDown={onBoardPointerDown}
      >
        {box && (
          <div
            className="kbmap-marquee"
            style={{ left: box.x, top: box.y, width: box.w, height: box.h }}
          />
        )}
        {rows.map(({ y, ks }) => (
          // An explicit, board-wide width (not flex auto-sizing) so every
          // row spans the same span of key-units and lines up column-for-
          // column with every other row — each key below is positioned by
          // its own real `x` within that shared span, not by flow order.
          // `top` is the vertical half of the same idea.
          <div
            className="kbrow"
            key={y}
            style={{
              width: `calc(var(--kb-u) * ${xBounds.span})`,
              top: `calc(var(--kb-u) * ${y - yBounds.min} + var(--kb-vgap) / 2 + var(--kb-pad))`,
            }}
          >
            {ks.map((k) => {
              const on = isSelected
                ? isSelected(k)
                : selected?.row === k.row && selected?.col === k.col;
              const w = k.w ?? 1;
              const bg = accent?.(k);
              // On a board previewing the LEDs, `accent` is not paint — it is
              // what the diode UNDER the cap is emitting, and the cap is an
              // object in front of it. `litCap` resolves that into the layers
              // keyboard-map.css assembles; null for a non-literal colour like
              // `var(--accent)`, which falls back to the flat fill.
              const led = lit && bg ? litCap(bg) : null;
              // What the legend actually sits on. Not `bg`: on a lit board the
              // cap is a fraction of the LED over a dark keycap, and measuring
              // the raw LED would pick black text for a key whose cap came out
              // nearly black.
              const capBg = led?.cap ?? bg;
              const g = gauge?.(k);
              const icon = KEY_ICON[k.label];
              const tipText = tip?.(k);
              return (
                <div
                  key={`${k.row}-${k.col}`}
                  data-row={k.row}
                  data-col={k.col}
                  className={`kbkey ${on ? 'sel' : ''} ${led ? 'is-lit' : ''}`}
                  style={{
                    left: `calc(var(--kb-u) * ${k.x - xBounds.min} + var(--kb-gap) / 2)`,
                    width: `calc(var(--kb-u) * ${w} - var(--kb-gap))`,
                    // On the look-only board the label keeps its own readable
                    // colour (+ shadow, see .kbmap-static) instead of flipping to
                    // the near-black --on-accent, which vanished on dim keys.
                    //
                    // On an interactive board the label colour is measured
                    // against the paint where the paint is a literal colour
                    // (`readableTextOn`), and only falls back to --on-accent
                    // for theme colours like `var(--accent)`. --on-accent is
                    // `#ffffff` under more than half the palettes, so a key
                    // painted white in the per-key editor rendered white on
                    // white.
                    ...(bg
                      ? {
                          // A lit key hands CSS the resolved LED and lets it
                          // build the cap out of a hotspot, a tint and a halo.
                          // An inline `background` here would beat every one of
                          // those layers — which is also why the hover
                          // background swap has never done anything on a
                          // painted key.
                          ...(led
                            ? {
                                ['--led' as string]: led.led,
                                ['--led-cap' as string]: led.cap,
                                ['--led-rim' as string]: led.rim,
                                ['--led-glow' as string]: led.glow,
                                ['--led-legend' as string]: led.legend,
                                ['--led-legend-shadow' as string]: led.legendShadow,
                                ...(flicker ? flickerVars(k.row, k.col) : {}),
                              }
                            : { background: bg }),
                          // A LIT key takes its legend colour from the LED —
                          // one value, since the board is the same dark object
                          // in either theme. It used to be set here only for
                          // an interactive board, so the per-key editor got
                          // per-key black/white legends while the global
                          // preview beside it got one flat `--text` for all of
                          // them: two boards showing the same thing in two
                          // different styles.
                          ...(interactive && !led && capBg
                            ? {
                                color:
                                  readableTextOn(capBg) ??
                                  THEME_FILL_TEXT[capBg] ??
                                  'var(--on-accent)',
                              }
                            : {}),
                        }
                      : {}),
                  }}
                  onMouseDown={
                    interactive
                      ? (e) => {
                          // When a marquee can start here, selection waits for
                          // pointerup (see onBoardPointerDown) — calling it now
                          // as well would select the key you started the drag
                          // from and then immediately replace the selection.
                          if (!marqueeFromKeys && !onKeyDrop) {
                            onSelect?.(
                              { row: k.row, col: k.col },
                              { shift: e.shiftKey, ctrl: e.ctrlKey || e.metaKey },
                            );
                          }
                          // Not while a box is being drawn: the press that
                          // starts one lands on a key too.
                          if (!dragFrom.current) onPaint?.({ row: k.row, col: k.col });
                        }
                      : undefined
                  }
                  onMouseEnter={
                    interactive
                      ? (e) => {
                          if (onPaint && e.buttons === 1 && !dragFrom.current)
                            onPaint({ row: k.row, col: k.col });
                        }
                      : undefined
                  }
                  onDoubleClick={
                    interactive && onKeyDoubleClick ? () => onKeyDoubleClick(k) : undefined
                  }
                  draggable={onKeyDragStart ? true : undefined}
                  onDragStart={
                    onKeyDragStart
                      ? (e) => {
                          // The browser takes the gesture over from here and
                          // stops sending pointermove, so a marquee this same
                          // press had begun would be left on screen forever.
                          dragFrom.current = null;
                          setBox(null);
                          onKeyDragStart(k, e);
                        }
                      : undefined
                  }
                >
                  {showLabels && (
                    <span className="kbkey-label">
                      {icon ? <Icon name={icon} size={13} /> : k.label}
                    </span>
                  )}
                  {cap && <span className="kbkey-cap">{cap(k)}</span>}
                  {tipText && (
                    <Tooltip text={tipText}>
                      <span className="kbkey-hit" />
                    </Tooltip>
                  )}
                  {g && (
                    <span className="kbkey-gauge">
                      {g.bands?.map((b, i) => (
                        <span
                          key={`band-${i}`}
                          className="kbkey-gauge-band"
                          style={{
                            top: `${b.fromPct}%`,
                            height: `${Math.max(0, b.toPct - b.fromPct)}%`,
                            background: b.color,
                          }}
                        />
                      ))}
                      <span
                        className="kbkey-gauge-fill"
                        style={{ height: `${Math.max(0, Math.min(100, g.fillPct))}%` }}
                      />
                      {g.ticks?.map((tk, i) => (
                        <span
                          key={`tick-${i}`}
                          className="kbkey-gauge-tick"
                          style={{ top: `${tk.pct}%`, background: tk.color }}
                        />
                      ))}
                    </span>
                  )}
                </div>
              );
            })}
          </div>
        ))}
      </div>
    </div>
  );
});
