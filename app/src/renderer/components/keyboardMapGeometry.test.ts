import { describe, expect, it } from 'vitest';
import { ANSI_75, ANSI_79_SG9047 } from '@shared/layouts';
import type { KeyLayoutEntry } from '@shared/types/keys';
import { GAP_U, bakedGapOf } from './KeyboardMap';

/**
 * The board has to read as a keyboard, which mostly comes down to one thing:
 * a 1u key must be SQUARE. It was not — the cap was a hardcoded 40px tall on a
 * 34px unit, and the gutter was subtracted from a width the vendor layout had
 * already subtracted it from, so a 1u key came out 0.75u wide by 1.18u tall.
 *
 * The two layouts express the gutter differently (see `bakedGapOf`), so this
 * checks the derived geometry for both rather than the constants.
 */

const U = 34;
/** Exactly what KeyboardMap writes into --kb-gap / --kb-h / each key's width. */
function geometry(keys: KeyLayoutEntry[], w = 1) {
  const baked = bakedGapOf(keys);
  return {
    baked,
    keyW: U * w - Math.max(0, U * (GAP_U - baked)),
    keyH: U * (1 - GAP_U),
  };
}

describe('KeyboardMap geometry', () => {
  it('measures the gutter ANSI_75 does not bake in', () => {
    // Generated by a `row()` helper: contiguous x, w: 1. Nothing baked in.
    expect(bakedGapOf(ANSI_75)).toBe(0);
  });

  it('measures the gutter the vendor layout bakes into its own w', () => {
    // 1.0 pitch, 0.87 wide keys — and the deliberate cluster gaps (before the
    // arrow block, between the F-key groups) must not be mistaken for it.
    expect(bakedGapOf(ANSI_79_SG9047)).toBeCloseTo(0.11, 2);
  });

  it.each([
    ['ANSI_75', ANSI_75, 1],
    ['ANSI_79_SG9047', ANSI_79_SG9047, 0.87],
  ])('draws a square 1u key on %s', (_name, keys, oneU) => {
    const g = geometry(keys as KeyLayoutEntry[], oneU as number);
    expect(Math.abs(g.keyW - g.keyH), `${g.keyW}px wide vs ${g.keyH}px tall`).toBeLessThan(1);
  });

  it('never asks for a negative gutter', () => {
    // A layout that bakes in MORE than GAP_U would otherwise push keys apart
    // by a negative gap, i.e. overlap them.
    const wide: KeyLayoutEntry[] = [
      { label: 'A', row: 0, col: 0, x: 0, y: 0, w: 0.5 },
      { label: 'B', row: 0, col: 1, x: 1, y: 0, w: 0.5 },
    ];
    expect(bakedGapOf(wide)).toBe(GAP_U);
  });
});

const rowsOf = (keys: KeyLayoutEntry[]) => [...new Set(keys.map((k) => k.y))].sort((a, b) => a - b);

describe.each([
  ['ANSI_75', ANSI_75],
  ['ANSI_79_SG9047', ANSI_79_SG9047],
])('%s vertical rhythm', (_name, keys) => {
  it('separates the function row from the number row', () => {
    // A 75% puts a quarter unit between them, and every other row is one unit
    // apart. Rendering rows in document order rather than by their own `y`
    // throws that gap away — which is what the board used to do.
    const rows = rowsOf(keys as KeyLayoutEntry[]);
    expect(rows[1]! - rows[0]!).toBeGreaterThan(1);
    expect(rows[2]! - rows[1]!).toBeCloseTo(1, 2);
  });
});
